/// История изменений по версиям — то, что видно в «О приложении».
///
/// Пишется для человека, который приложение не собирает: дизайнера,
/// аналитика, тестировщика. Поэтому формулировки про то, **что изменилось на
/// экране**, а не про то, как это устроено внутри. «Счётчик лайков совпадает
/// в карточке и внутри статьи» — да; «оптимистичный оверлей вынесен в общий
/// провайдер» — нет.
///
/// Список лежит в приложении, а не приходит с сервера: запись описывает
/// конкретную сборку, и должна попадать к пользователю вместе с ней.
library;

enum ChangeKind {
  /// Появилось то, чего не было.
  added('Новое'),

  /// Было и стало работать/выглядеть иначе.
  changed('Изменено'),

  /// Работало неправильно — починили.
  fixed('Исправлено');

  const ChangeKind(this.label);

  final String label;
}

class ChangelogEntry {
  const ChangelogEntry(this.kind, this.text);

  final ChangeKind kind;
  final String text;
}

class AppRelease {
  const AppRelease({
    required this.version,
    required this.entries,
    this.date,
    this.inProgress = false,
  });

  final String version;

  /// Дата выпуска. У версии, которая ещё собирается, её нет.
  final String? date;
  final bool inProgress;
  final List<ChangelogEntry> entries;

  List<ChangelogEntry> entriesOf(ChangeKind kind) =>
      entries.where((entry) => entry.kind == kind).toList(growable: false);
}

