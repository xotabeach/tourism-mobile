/// Документы раздела «О приложении».
///
/// Тексты лежат в коде, а не тянутся с сервера: их читают редко, но иногда
/// без сети (в горах), и страница «не удалось загрузить» вместо
/// пользовательского соглашения выглядит хуже, чем чуть более тяжёлый
/// бандл. Обновляются они вместе с версией приложения — так же, как
/// история изменений.
///
/// Формулировки — рабочая редакция продукта, а не заключение юриста:
/// перед публикацией в сторах их нужно вычитать.
class LegalDocument {
  const LegalDocument({
    required this.id,
    required this.title,
    required this.subtitle,
    required this.icon,
    required this.sections,
    this.updated,
  });

  /// Идентификатор в пути: `/settings/about/doc/<id>`.
  final String id;
  final String title;

  /// Вторая строка в списке — она же объясняет, зачем сюда заходить.
  final String subtitle;
  final IconData icon;
  final String? updated;
  final List<LegalSection> sections;
}

class LegalSection {
  const LegalSection({required this.heading, required this.paragraphs});

  final String heading;
  final List<String> paragraphs;
}

